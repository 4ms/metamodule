#!/usr/bin/env python3
"""
Generate the GUI's icon images for a build with a GUI scale (METAMODULE_UI_SCALE, see
gui/ui_scale.h) from their SVGs in graphics/ui/.

Only the icons that are not a glyph in ui_font_icons are images (see ICONS).
MP1 uses the 1x images in this dir (ui_img_<name>.c). Builds with a GUI scale use the ones
this writes to scaled/, which must be made at the same scale:

    ./generate_scaled_images.py --scale 2

Requires rsvg-convert (librsvg).
"""

import argparse
import struct
import subprocess
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SVG_DIR = HERE.parents[5] / "graphics" / "ui"
OUT_DIR = HERE / "scaled"

# image name -> SVG in graphics/ui
ICONS = {
    "knob": "knob.svg",
    "knob_pressed": "knob_pressed.svg",
}


def svg_size(svg: Path) -> tuple[float, float]:
    import xml.etree.ElementTree as ET

    root = ET.parse(svg).getroot()
    return float(root.get("width")), float(root.get("height"))


def decode_png(data: bytes) -> tuple[int, int, list[bytes]]:
    """Returns width, height and rows of RGBA bytes of an 8-bit RGBA PNG"""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("rsvg-convert did not write a PNG")
    pos = 8
    idat = b""
    width = height = 0
    while pos < len(data):
        (length,) = struct.unpack(">I", data[pos : pos + 4])
        kind = data[pos + 4 : pos + 8]
        body = data[pos + 8 : pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, color_type, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if (depth, color_type, interlace) != (8, 6, 0):
                sys.exit("Expected an 8-bit RGBA PNG")
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length

    raw = zlib.decompress(idat)
    stride = width * 4
    rows = []
    prev = bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        filter_type = raw[start]
        line = bytearray(raw[start + 1 : start + 1 + stride])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if filter_type == 1:
                line[i] = (line[i] + a) & 0xFF
            elif filter_type == 2:
                line[i] = (line[i] + b) & 0xFF
            elif filter_type == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 0xFF
            elif filter_type == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                paeth = a if pa <= pb and pa <= pc else b if pb <= pc else c
                line[i] = (line[i] + paeth) & 0xFF
        rows.append(bytes(line))
        prev = line
    return width, height, rows


def write_c(name: str, svg: Path, scale: float, width: int, height: int, rows: list[bytes]):
    symbol = f"ui_img_{name}"

    def pixels(encode):
        lines = []
        for row in rows:
            px = []
            for x in range(width):
                px += encode(*row[x * 4 : x * 4 + 4])
            lines.append("\t" + "".join(f"0x{b:02X}," for b in px))
        return "\n".join(lines)

    def rgb565(r, g, b, a):
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        return [c & 0xFF, c >> 8, a]

    def rgb565_swapped(r, g, b, a):
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        return [c >> 8, c & 0xFF, a]

    def argb8888(r, g, b, a):
        return [b, g, r, a]

    text = f"""// Generated by generate_scaled_images.py --scale {scale:g}
// from graphics/ui/{svg.name}

#ifdef LV_LVGL_H_INCLUDE_SIMPLE
#include "lvgl.h"
#else
#include "lvgl/lvgl.h"
#endif

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_data[] = {{
#if LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP == 0
{pixels(rgb565)}
#elif LV_COLOR_DEPTH == 16
{pixels(rgb565_swapped)}
#elif LV_COLOR_DEPTH == 32
{pixels(argb8888)}
#else
#error "Unsupported LV_COLOR_DEPTH"
#endif
}};

const lv_img_dsc_t {symbol} = {{
	.header.always_zero = 0,
	.header.w = {width},
	.header.h = {height},
	.data_size = sizeof({symbol}_data),
	.header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,
	.data = {symbol}_data,
}};
"""
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / f"{symbol}.c").write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--scale", type=float, default=2.0, help="Size multiplier vs. the MP1 images (default 2)")
    args = parser.parse_args()

    for name, svg_name in ICONS.items():
        svg = SVG_DIR / svg_name
        w, h = svg_size(svg)
        width, height = round(w * args.scale), round(h * args.scale)
        cmd = ["rsvg-convert", "-w", str(width), "-h", str(height), "-f", "png", str(svg)]
        png = subprocess.run(cmd, check=True, capture_output=True).stdout
        width, height, rows = decode_png(png)
        write_c(name, svg, args.scale, width, height, rows)
        print(f"ui_img_{name}: {svg_name} x{args.scale:g} -> {width}x{height}")


if __name__ == "__main__":
    main()
